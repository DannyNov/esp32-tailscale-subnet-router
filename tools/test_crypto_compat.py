"""Real TF-PSA-Crypto host KAT. No devices; compilation failure is test failure.

Requires --sdk pointing to the resolved IDF 6.1 package. Configuration is
host-only. SHA source hashes and commands are recorded beside test output.
SPDX-License-Identifier: MIT
"""
import argparse, hashlib, json, os, pathlib, shlex, subprocess, sys

root = pathlib.Path(__file__).resolve().parents[1]
p = argparse.ArgumentParser()
p.add_argument('--sdk', required=True, type=pathlib.Path)
p.add_argument('--cc', default=os.environ.get('CC', 'cc'))
a = p.parse_args()
sdk = a.sdk.resolve()
psa = sdk/'components/mbedtls/mbedtls/tf-psa-crypto'
out = root/'build/crypto-compat'
out.mkdir(parents=True, exist_ok=True)
vectors = ['/* Independently generated by Python hashlib; synthetic data only. */',
           'struct password_vector { unsigned seed; const char *text, *fixture; };',
           'static const struct password_vector password_vectors[] = {']
for seed, text in [(0,'password'), (128,'test password with spaces'),
                   (240,'p@ss:word!'), (7,'x'*1024), (19,'пароль UTF-8')]:
    salt = bytes((seed+i) % 256 for i in range(16))
    fixture = salt.hex()+':'+hashlib.sha256(salt+text.encode()).hexdigest()
    # UTF-8 encoded byte escapes prevent locale/compiler encoding drift.
    literal = '"'+''.join('\\x%02x'%b for b in text.encode())+'"'
    vectors.append('{%d,%s,%s},' % (seed,literal,json.dumps(fixture)))
vectors += ['};', 'struct telemetry_vector { unsigned char mac[6]; const char *id; };',
            'static const struct telemetry_vector telemetry_vectors[] = {']
for mac in [bytes(6), bytes.fromhex('020000000001'), bytes.fromhex('ffffffffffff')]:
    ident = hashlib.sha256(mac+b'esp32-tailscale-router-v1').digest()[:8].hex()
    ident += hashlib.sha256(b'esp32-tailscale-v1'+ident.encode()).digest()[:1].hex()
    vectors.append('{{%s},%s},' % (','.join(str(b) for b in mac),json.dumps(ident)))
vectors.append('};')
(out/'crypto_vectors.h').write_text('\n'.join(vectors)+'\n')
sources = []
for folder in ['core','drivers/builtin/src','platform','dispatch','extras','utilities']:
    sources += sorted((psa/folder).glob('*.c'))
assert sources and (psa/'include/psa/crypto.h').is_file(), 'Missing real TF-PSA sources'
cc = shlex.split(a.cc, posix=os.name != 'nt')
cc = [s.strip('"') for s in cc]
exe = out/('crypto-kat.exe' if os.name == 'nt' else 'crypto-kat')
command = cc+['-O0','-g','-UNDEBUG','-std=c11',
              '-DTF_PSA_CRYPTO_CONFIG_FILE="crypto_config.h"',
              '-I'+str(root/'tests/host'), '-I'+str(root/'tests/host/crypto_stubs'),
              '-I'+str(root/'components/web_password/include'), '-I'+str(out)]
command += ['-I'+str(psa/f) for f in ['include','core','platform','dispatch','extras',
                                    'utilities','drivers/builtin/include','drivers/builtin/src']]
command += [str(root/'tests/host/crypto_kat.c')] + [str(s) for s in sources]
if os.name == 'nt': command += ['-lbcrypt','-ladvapi32']
command += ['-o',str(exe)]
manifest = {'host_only':True,'target_abi_proven':False,'command':command,
            'sdk_package':json.loads((sdk/'package.json').read_text()),
            'source_sha256':{str(s.relative_to(sdk)):hashlib.sha256(s.read_bytes()).hexdigest()
                             for s in sources+sorted((psa/'include').rglob('*.h'))},
            'config_sha256':hashlib.sha256((root/'tests/host/crypto_config.h').read_bytes()).hexdigest()}
result = subprocess.run(command,stdout=subprocess.PIPE,stderr=subprocess.STDOUT)
(out/'compile.log').write_bytes(result.stdout)
manifest['compile_exit'] = result.returncode
if result.returncode == 0:
    result = subprocess.run([str(exe)],stdout=subprocess.PIPE,stderr=subprocess.STDOUT)
    (out/'kat.log').write_bytes(result.stdout)
    manifest['kat_exit'] = result.returncode
(out/'manifest.json').write_text(json.dumps(manifest,indent=2))
print(result.stdout.decode(errors='replace'), end='')
sys.exit(result.returncode)
